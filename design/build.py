"""Generate every platform's design files from design/tokens.json and design/icons.json.

    python design/build.py

Writes: metaclean/static/tokens.css, metaclean/static/icons.svg, the manifest and the share card.
The IBM Plex fonts (OFL) are committed in metaclean/static/fonts.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design/tokens.json").read_text())
ICONS = {k: v for k, v in json.loads((ROOT / "design/icons.json").read_text()).items() if k != "_"}
FONT_SRC = {
    "IBMPlexSans": ROOT / "mobile/node_modules/@expo-google-fonts/ibm-plex-sans",
    "IBMPlexMono": ROOT / "mobile/node_modules/@expo-google-fonts/ibm-plex-mono",
    "IBMPlexSansCondensed": ROOT / "mobile/node_modules/@expo-google-fonts/ibm-plex-sans-condensed",
}
HEADER = "/* Generated by design/build.py from design/tokens.json. Do not edit by hand. */\n"


def theme_vals(kind):
    out = {"light": {}, "dark": {}}
    for t in T[kind]["tokens"]:
        v = t["value"]
        for th in out:
            out[th][t["name"]] = v if isinstance(v, str) else v.get(th, v["light"])
    return out


def css():
    colors, shadows = theme_vals("color"), theme_vals("shadow")
    decl = lambda th: "".join(f"  --{k}: {v};\n" for k, v in {**colors[th], **shadows[th]}.items())
    flat = "".join(f"  --{t['name']}: {t['value']};\n" for fam in ("spacing", "radius", "duration", "easing", "layer")
                   if fam in T for t in T[fam]["tokens"])
    fams = "".join(f"  --font-{k}: {v};\n" for k, v in T["type"]["families"].items())
    faces = ""
    for f in T["type"]["fonts"]:
        name = Path(f["file"]).name
        w2 = name.replace(".ttf", ".woff2")
        faces += (f"@font-face {{ font-family: \"{f['family']}\"; src: url(\"fonts/{w2}\") format(\"woff2\"), url(\"fonts/{name}\") format(\"truetype\"); "
                  f"font-weight: {f['weight']}; font-style: normal; font-display: swap; }}\n")
    styles = ""
    for g in T["type"]["groups"]:
        for s in g["styles"]:
            ls = f" letter-spacing: {s['letterSpacing']};" if "letterSpacing" in s else ""
            tt = " text-transform: uppercase;" if s["name"] == "overline" else ""
            styles += (f".t-{s['name']} {{{tt} font-family: var(--font-{g['family']}); font-size: {s['fontSize']}; "
                       f"line-height: {s['lineHeight']}; font-weight: {s['fontWeight']};{ls} }}\n")
    return (HEADER + faces + ":root {\n" + decl("light") + flat + fams + "  color-scheme: light;\n}\n"
            "@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n"
            + decl("dark").replace("  --", "    --") + "    color-scheme: dark;\n  }\n}\n"
            ":root[data-theme=\"dark\"] {\n" + decl("dark") + "  color-scheme: dark;\n}\n" + styles)


def glyph(inner: str) -> str:
    """Icon body with explicit presentation attributes, so it renders the same in a sprite, inline or on mobile."""
    inner = inner.replace('class="fill"', 'fill="currentColor" stroke="none"')
    return ('<g fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" '
            f'stroke-linejoin="round">{inner}</g>')


def sprite():
    syms = "".join(f'<symbol id="i-{k}" viewBox="0 0 24 24">{glyph(v)}</symbol>' for k, v in ICONS.items())
    return '<svg xmlns="http://www.w3.org/2000/svg"><!-- Generated by design/build.py -->' + syms + "</svg>\n"


def ts():
    colors, shadows = theme_vals("color"), theme_vals("shadow")
    LEGACY = {"bg": "paper", "surface": "paper", "surface-sunk": "paper-2", "line": "rule", "ink-muted": "ink-2",
              "ink-subtle": "ink-3", "lagoon": "ink", "on-lagoon": "on-ink", "lagoon-soft": "paper-2", "flare": "on-highlight",
              "flare-soft": "highlight", "warn": "alert", "cat-location": "ink", "cat-device": "ink", "cat-personal": "ink",
              "cat-ai": "ink", "cat-hidden": "ink-2", "good": "ink"}
    for th in colors:
        for old, new in LEGACY.items():
            colors[th].setdefault(old, colors[th][new])
    sizes = {t["name"]: int(re.sub(r"\D", "", t["value"]) or 0) for fam in ("spacing", "radius") for t in T[fam]["tokens"]}
    for old, new in {"radius-tile": "radius-2", "radius-card": "radius-2", "radius-sheet": "radius-3", "radius-pill": "radius-2"}.items():
        sizes.setdefault(old, sizes[new])
    styles = {}
    for g in T["type"]["groups"]:
        for s in g["styles"]:
            fam = {"mono": "IBMPlexMono", "display": "IBMPlexSansCondensed"}.get(g["family"], "IBMPlexSans")
            w = s["fontWeight"]
            weight_name = {400: "400Regular", 500: "500Medium", 600: "600SemiBold", 700: "700Bold"}[w]
            st = {"fontFamily": f"{fam}_{weight_name}", "fontSize": int(s["fontSize"][:-2]),
                  "lineHeight": int(s["lineHeight"][:-2])}
            if "letterSpacing" in s:
                st["letterSpacing"] = float(s["letterSpacing"][:-2])
            styles[s["name"]] = st
    return ("// Generated by design/build.py from design/tokens.json and design/icons.json. Do not edit by hand.\n"
            f"export const colors = {json.dumps(colors, indent=2)} as const;\n"
            f"export const size = {json.dumps(sizes, indent=2)} as const;\n"
            f"export const type = {json.dumps(styles, indent=2)} as const;\n"
            "export const icons: Record<string, string> = "
            + json.dumps({k: f'<svg viewBox="0 0 24 24">{glyph(v)}</svg>' for k, v in ICONS.items()}, indent=2) + ";\n"
            "export type IconName = keyof typeof icons;\n")


def fonts():
    out = ROOT / "metaclean/static/fonts"
    out.mkdir(parents=True, exist_ok=True)
    for f in T["type"]["fonts"]:
        name = Path(f["file"]).name
        fam, rest = name.split("_", 1)
        shutil.copy(FONT_SRC[fam] / rest.replace(".ttf", "") / name, out / name)
    try:  # woff2 is ~half the size of ttf; needs fonttools + brotli (pip install fonttools brotli)
        from fontTools.ttLib import TTFont
        for f in T["type"]["fonts"]:
            ttf = out / Path(f["file"]).name
            font = TTFont(ttf)
            font.flavor = "woff2"
            font.save(ttf.with_suffix(".woff2"))
    except ImportError:
        print("fonttools not installed: skipped woff2")
    for old in out.glob("*"):
        if old.name.startswith(("Bricolage", "Figtree", "OFL-B", "OFL-F")):
            old.unlink()
    shutil.copy(FONT_SRC["IBMPlexSans"] / "LICENSE_FONT", out / "OFL-IBMPlexSans.txt")
    shutil.copy(FONT_SRC["IBMPlexMono"] / "LICENSE_FONT", out / "OFL-IBMPlexMono.txt")
    shutil.copy(FONT_SRC["IBMPlexSansCondensed"] / "LICENSE_FONT", out / "OFL-IBMPlexSansCondensed.txt")


def images():
    """App icons and the social-share card, drawn from the tokens (needs Pillow: run with the project venv)."""
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        print("Pillow not installed: skipped icons")
        return
    light = theme_vals("color")["light"]
    paper, paper2, ink, ink2, hl, rule = (light[k] for k in ("paper", "paper-2", "ink", "ink-2", "highlight", "rule"))

    def mark(size, pad=0.0, ground=None):
        """The mark: a frame (the photo), a highlighted line (a detail found) and a redaction bar (a detail removed)."""
        im = Image.new("RGBA", (size, size), ground or (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        o = size * pad; u = (size - 2 * o) / 32
        R = lambda x0, y0, x1, y1: [o + x0 * u, o + y0 * u, o + x1 * u - 1, o + y1 * u - 1]
        d.rectangle(R(0, 0, 32, 32), fill=ink)
        d.rectangle(R(3, 3, 29, 29), fill=paper)
        d.rectangle(R(7, 9, 25, 13), fill=hl)
        d.rectangle(R(7, 17, 25, 23), fill=ink)
        return im

    st = ROOT / "metaclean/static"
    big = mark(1024)
    for name, size in [("icon-192.png", 192), ("icon-512.png", 512)]:
        big.resize((size, size), Image.LANCZOS).save(st / name)
    full = Image.new("RGBA", (1024, 1024), paper)
    full.alpha_composite(mark(1024, pad=0.16))
    full.resize((512, 512), Image.LANCZOS).save(st / "icon-maskable-512.png")
    full.convert("RGB").resize((180, 180), Image.LANCZOS).save(st / "apple-touch-icon.png")

    # social card 1200x630: headline left, an EXIF readout right
    W, H = 1200, 630
    card = Image.new("RGB", (W, H), paper)
    d = ImageDraw.Draw(card)
    fonts = ROOT / "metaclean/static/fonts"
    sans = lambda w, s: ImageFont.truetype(str(fonts / f"IBMPlexSans_{w}.ttf"), s)
    mono = lambda w, s: ImageFont.truetype(str(fonts / f"IBMPlexMono_{w}.ttf"), s)
    card.paste(mark(44).convert("RGB"), (80, 70), mark(44))
    d.text((138, 74), "unmeta", font=sans("600SemiBold", 32), fill=ink)
    # the headline as on the page: condensed, with the highlighter on "before"
    disp = ImageFont.truetype(str(fonts / "IBMPlexSansCondensed_700Bold.ttf"), 76)
    lines, y = ["Clean your photos", "and videos before", "you share them."], 150
    for ln in lines:
        if "before" in ln:
            pre = ln[: ln.index("before")]
            bx = 80 + d.textlength(pre, font=disp)
            d.rectangle([bx - 4, y + 30, bx + d.textlength("before", font=disp) + 4, y + 78], fill=hl)
        d.text((80, y), ln, font=disp, fill=ink)
        y += 76
    d.text((80, 440), "See what they reveal and remove it.\nIn your browser. No loss of quality.", font=sans("400Regular", 28), fill=ink2, spacing=10)
    x0, y0 = 760, 150
    d.rectangle([x0, y0, 1120, 470], outline=rule, width=2)
    lab, val = mono("500Medium", 17), mono("400Regular", 22)
    rows = [("FILE", "IMG_2041.HEIC", None), ("GPS", "51.5072, -0.1275", "hl"), ("DEVICE", "iPhone 15 Pro", "hl"),
            ("OWNER", "Jane Doe", "hl"), ("AI", "Made with AI", "redact")]
    for i, (k, v, mode) in enumerate(rows):
        y = y0 + 28 + i * 58
        if i:
            d.line([x0 + 2, y - 15, 1118, y - 15], fill=rule, width=1)
        d.text((x0 + 24, y + 4), k, font=lab, fill=ink2)
        tw = d.textlength(v, font=val)
        if mode == "hl":
            d.rectangle([x0 + 128, y - 3, x0 + 136 + tw, y + 29], fill=hl)
        if mode == "redact":
            d.rectangle([x0 + 128, y - 3, x0 + 136 + tw, y + 29], fill=ink)
        else:
            d.text((x0 + 132, y), v, font=val, fill=ink)
    card.save(st / "og.png", optimize=True)


def manifest():
    light, dark = theme_vals("color")["light"], theme_vals("color")["dark"]
    return json.dumps({
        "id": "/", "name": "UnMeta", "short_name": "UnMeta", "categories": ["photo", "utilities", "privacy"],
        "description": "Remove hidden metadata from photos, videos and documents in your browser. Nothing is uploaded.",
        "start_url": "/", "scope": "/", "display": "browser", "lang": "en-GB",
        "background_color": light["paper"], "theme_color": light["ink"],
        "icons": [
            {"src": "/static/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "/static/icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "/static/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
            {"src": "/static/mark.svg", "sizes": "any", "type": "image/svg+xml"},
        ],
    }, indent=2)


def inline_sprite():
    """Put the icon sprite inside index.html, so the page never has to fetch it (connect-src 'none')."""
    p = ROOT / "metaclean/static/index.html"
    html = p.read_text()
    block = ("<!--ICONS:start-->" + sprite().strip().replace("<svg xmlns", '<svg hidden aria-hidden="true" xmlns', 1)
             + "<!--ICONS:end-->")
    if "<!--ICONS:start-->" in html:
        html = re.sub(r"<!--ICONS:start-->.*?<!--ICONS:end-->", lambda m: block, html, flags=re.S)
    else:
        html = html.replace("<body data-screen=\"home\">", "<body data-screen=\"home\">\n" + block, 1)
    p.write_text(html)


(ROOT / "metaclean/static/tokens.css").write_text(css())
(ROOT / "metaclean/static/icons.svg").write_text(sprite())
(ROOT / "metaclean/static/mark.svg").write_text((ROOT / "design/mark.svg").read_text())
icon_dir = ROOT / "design/icons"
icon_dir.mkdir(exist_ok=True)
for k, v in ICONS.items():
    (icon_dir / f"{k}.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" color="#111111">{glyph(v)}</svg>\n')
images()
(ROOT / "metaclean/static/manifest.webmanifest").write_text(manifest())
inline_sprite()
print("ok")
